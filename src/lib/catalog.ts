const INDEX = new Map<string, CatalogEntry>();
for (const e of CATALOG) {
	INDEX.set(e.name.toLowerCase(), e);
	for (const a of e.aliases ?? []) INDEX.set(a.toLowerCase(), e);
}

export function catalogByExactName(name: string): CatalogEntry | undefined {
	return INDEX.get(name.trim().toLowerCase());
}

